"""
Runs the test suites and evaluations and writes docs/results/summary.{json,md}, then updates the results table in
README.md between the RESULTS markers. Every number in that table comes from this script's own run output.

    backend/.venv/Scripts/python.exe scripts/collect_results.py            # Windows
    backend/.venv/bin/python scripts/collect_results.py                    # Linux/macOS
    ... --skip-evals        reuse docs/results/*.json instead of re-running the (deterministic) evaluations
    ... --with-integration  also run tests/integration (needs the Docker labs, Postgres and a cluster; see README)
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND, FRONTEND, RESULTS = ROOT / "backend", ROOT / "frontend", ROOT / "docs" / "results"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def run(cmd, cwd, env=None):
    print("+", " ".join(map(str, cmd)), flush=True)
    return subprocess.run(cmd, cwd=cwd, env={**os.environ, **(env or {})}, capture_output=True, text=True)


def junit_counts(path: Path) -> dict:
    root = ET.parse(path).getroot()
    suite = root if root.tag == "testsuite" else root.find("testsuite")
    tests, fails = int(suite.get("tests")), int(suite.get("failures")) + int(suite.get("errors"))
    skipped = int(suite.get("skipped"))
    return {"total": tests, "passed": tests - fails - skipped, "failed": fails, "skipped": skipped}


def backend(with_integration: bool) -> dict:
    """Default suite (no external systems), then optionally the integration suite against real systems."""
    junit, cov = BACKEND / "junit.xml", BACKEND / "coverage.json"
    base = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"]
    r = run(base + ["--cov=app", f"--cov-report=json:{cov}", f"--junitxml={junit}"], BACKEND,
            {"KUBE_INTEGRATION": "", "RENEWAL_INTEGRATION": "", "PG_TEST_URL": ""})
    counts = junit_counts(junit)
    counts["coverage_percent"] = round(json.loads(cov.read_text())["totals"]["percent_covered"], 1)
    counts["exit_code"] = r.returncode
    counts["integration"] = None
    if with_integration:
        ij = BACKEND / "junit-integration.xml"
        env = {"KUBE_INTEGRATION": "1", "RENEWAL_INTEGRATION": "1"}
        ri = run(base + ["tests/integration", f"--junitxml={ij}"], BACKEND, env)
        counts["integration"] = {**junit_counts(ij), "exit_code": ri.returncode}
    return counts


def frontend() -> dict:
    npm = shutil.which("npm")
    r = run([npm, "run", "test:coverage", "--", "--reporter=json", f"--outputFile={FRONTEND / 'vitest.json'}"], FRONTEND)
    data = json.loads((FRONTEND / "vitest.json").read_text())
    total = json.loads((FRONTEND / "coverage" / "coverage-summary.json").read_text())["total"]
    return {"total": data["numTotalTests"], "passed": data["numPassedTests"], "failed": data["numFailedTests"],
            "coverage": {k: total[k]["pct"] for k in ("statements", "branches", "functions", "lines")},
            "exit_code": r.returncode}


def evals(skip: bool) -> tuple[dict, dict]:
    if not skip:
        run([sys.executable, "-W", "ignore", "-m", "app.ml.evaluate", "--docs", str(RESULTS)], BACKEND)
        run([sys.executable, "-W", "ignore", "-m", "app.agent.eval", "--docs", str(RESULTS)], BACKEND)
    return (json.loads((RESULTS / "risk_eval.json").read_text()),
            json.loads((RESULTS / "agent_eval_scripted.json").read_text()))


def commit() -> str:
    r = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True)
    return r.stdout.strip() or "unknown"


def table(s: dict) -> str:
    b, f, risk, agent = s["backend"], s["frontend"], s["risk"], s["agent_scripted"]
    t = risk["test"]
    gb, base = t["gradient_boosting"], t["baseline_days_to_expiry"]
    ci = risk["bootstrap_vs_baseline"]["gradient_boosting"]
    integ = b["integration"]
    integ_row = (f"| Backend integration tests (real Pebble ACME CA, Vault, PostgreSQL, Kubernetes) | {integ['passed']} passed, "
                 f"{integ['failed']} failed, {integ['skipped']} skipped | start the labs (see README), then `KUBE_INTEGRATION=1 "
                 f"RENEWAL_INTEGRATION=1 PG_TEST_URL=... pytest tests/integration` |\n") if integ else (
        "| Backend integration tests | not run in this report | see README \"Testing and CI\" |\n")
    cov = f["coverage"]
    return f"""<!-- generated by scripts/collect_results.py at {s['generated_at']} (commit {s['commit']}); do not edit by hand -->
| What | Result | How to reproduce |
|---|---|---|
| Backend tests (default suite, no external systems) | {b['passed']} passed, {b['failed']} failed, {b['skipped']} skipped (the skipped ones are the integration tests) | `cd backend && pytest` |
{integ_row.rstrip()}
| Backend line coverage | {b['coverage_percent']}% | `cd backend && pytest --cov=app` |
| Frontend tests | {f['passed']} passed, {f['failed']} failed | `cd frontend && npm test` |
| Frontend coverage | statements {cov['statements']}%, branches {cov['branches']}%, functions {cov['functions']}%, lines {cov['lines']}% | `cd frontend && npm run test:coverage` |
| Risk model, **synthetic data only** | ROC-AUC {gb['roc_auc']:.3f} vs {base['roc_auc']:.3f} for the days-to-expiry rule; PR-AUC {gb['pr_auc']:.3f} vs {base['pr_auc']:.3f}; F1 {gb['f1']:.3f} vs {base['f1']:.3f} (precision {gb['precision']:.3f}, recall {gb['recall']:.3f}) | `cd backend && python -m app.ml.evaluate` |
| Risk model gap vs rule (95% bootstrap CI) | ROC-AUC {ci['roc_auc_delta_95ci'][0]:+.3f} to {ci['roc_auc_delta_95ci'][1]:+.3f} | same command |
| Agent eval, **scripted stand-in model** | {agent['passed']}/{agent['cases_counted']} cases ({agent['success_rate']:.1%}). Tested workflow behavior (tools, guardrails, approval gate), **not model accuracy** | `cd backend && python -m app.agent.eval` |
| Agent eval, live Gemini | **not run** (no API key during development) | `python -m app.agent.eval --backend live --record c.json` |
"""


def update_docs(md: str) -> None:
    """Fill the results table between the RESULTS markers in every document that carries one."""
    for rel in ("README.md", "docs/RESUME_CLAIMS.md"):
        p = ROOT / rel
        s = p.read_text(encoding="utf-8")
        if START not in s:
            raise SystemExit(f"{rel} has no {START} marker")
        head, rest = s.split(START, 1)
        _, tail = rest.split(END, 1)
        p.write_text(f"{head}{START}\n{md}{END}{tail}", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--skip-evals", action="store_true")
    ap.add_argument("--with-integration", action="store_true")
    a = ap.parse_args()
    RESULTS.mkdir(parents=True, exist_ok=True)
    risk, agent = evals(a.skip_evals)
    summary = {"generated_at": datetime.now(UTC).isoformat(timespec="seconds"), "commit": commit(),
               "backend": backend(a.with_integration), "frontend": frontend(), "risk": risk, "agent_scripted": agent}
    summary["agent_scripted"].pop("results", None)  # keep the summary small; full detail is in agent_eval_scripted.json
    (RESULTS / "summary.json").write_text(json.dumps(summary, indent=1))
    md = table(summary)
    (RESULTS / "summary.md").write_text(md)
    update_docs(md)
    print(md)
    ib = summary["backend"]["integration"] or {"failed": 0, "exit_code": 0}
    failed = summary["backend"]["failed"] + summary["frontend"]["failed"] + ib["failed"]
    raise SystemExit(1 if failed or summary["backend"]["exit_code"] or summary["frontend"]["exit_code"] else 0)


if __name__ == "__main__":
    main()
